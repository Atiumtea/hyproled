#!/usr/bin/env python3
"""Generate compact symbolic mask/Pixel Shift icons and their Waybar CSS."""

from __future__ import annotations

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "assets"
OUTPUT_DIR = ASSET_DIR / "icons"
CSS_OUTPUT = ASSET_DIR / "waybar-icons.css"

# Top: GLSL positions 2, 3. Bottom: GLSL positions 0, 1.
# The bit string is printed MSB-first (positions 3..0).
PIXEL_PATHS = {
    0: "M12 12 L12 21.2 A9.2 9.2 0 0 1 2.8 12 Z",   # bottom-left
    1: "M12 12 L21.2 12 A9.2 9.2 0 0 1 12 21.2 Z",  # bottom-right
    2: "M12 12 L2.8 12 A9.2 9.2 0 0 1 12 2.8 Z",    # top-left
    3: "M12 12 L12 2.8 A9.2 9.2 0 0 1 21.2 12 Z",  # top-right
}

DIRECTION_ANGLES = {
    "north": -90.0,
    "north-east": -45.0,
    "east": 0.0,
    "south-east": 45.0,
    "south": 90.0,
    "south-west": 135.0,
    "west": 180.0,
    "north-west": 225.0,
}
DIRECTION_CODES = {
    "north": "N",
    "north-east": "NE",
    "east": "E",
    "south-east": "SE",
    "south": "S",
    "south-west": "SW",
    "west": "W",
    "north-west": "NW",
}
DIRECTIONS = tuple(DIRECTION_ANGLES)
MASK_TRANSLATE = "translate(2.6 2.6) scale(0.95)"

OUTER_RING = (
    '<path id="outer-ring" class="foreground" fill-rule="evenodd" '
    'd="M12 1.5 A10.5 10.5 0 1 1 12 22.5 '
    'A10.5 10.5 0 1 1 12 1.5 Z '
    'M12 3 A9 9 0 1 0 12 21 A9 9 0 1 0 12 3 Z" />'
)
GRID_VERTICAL = (
    '<path id="grid-vertical" class="foreground" '
    'd="M11.35 3 H12.65 V21 H11.35 Z" />'
)
GRID_HORIZONTAL = (
    '<path id="grid-horizontal" class="foreground" '
    'd="M3 11.35 H21 V12.65 H3 Z" />'
)
ERROR_MARK = (
    '<path id="error-mark" class="foreground" '
    'd="M7.1 5.9 L12 10.8 L16.9 5.9 L18.1 7.1 '
    'L13.2 12 L18.1 16.9 L16.9 18.1 L12 13.2 '
    'L7.1 18.1 L5.9 16.9 L10.8 12 L5.9 7.1 Z" />'
)
SVG_HEADER = (
    '<svg xmlns="http://www.w3.org/2000/svg" '
    'width="28" height="28" viewBox="0 0 28 28">'
)
CSS_HEADER = """/* Generated by scripts/generate-icons.py. Do not edit manually. */
/* Uses plain SVG URLs; dotfiles bake the active Stylix colors into build assets. */
/* The 0000 pattern is Pixel Shift-only; center has no directional suffix. */

"""


def mask_for_state(phase: int, off_pixels: int) -> str:
    """Return the four-bit mask used by the production shader."""
    if phase not in range(4):
        raise ValueError("phase must be between 0 and 3")
    if off_pixels not in (1, 2, 3):
        raise ValueError("off_pixels must be between 1 and 3")
    bits = 0
    for pos in range(4):
        if (pos - phase) % 4 < off_pixels:
            bits |= 1 << pos
    return f"{bits:04b}"


def active_masks() -> list[str]:
    return sorted({
        mask_for_state(phase, off_pixels)
        for phase in range(4)
        for off_pixels in (1, 2, 3)
    })


def all_masks() -> list[str]:
    """Include 0000, the shared no-mask/Pixel Shift-only pattern."""
    return ["0000", *active_masks()]


def icon_filename(mask: str, direction: str = "center") -> str:
    """Build the canonical compact filename from mask and direction."""
    if len(mask) != 4 or set(mask) - {"0", "1"}:
        raise ValueError(f"invalid four-bit mask: {mask!r}")
    if direction == "center":
        return f"hyproled-{mask}.svg"
    try:
        code = DIRECTION_CODES[direction]
    except KeyError as exc:
        raise ValueError(f"unsupported direction: {direction}") from exc
    return f"hyproled-{mask}-{code}.svg"


def direction_sector(direction: str) -> str:
    """Create one full-width annular sector outside the central icon."""
    angle = math.radians(DIRECTION_ANGLES[direction])
    half_width = math.radians(22.5)
    outer_radius = 13.15
    # Match the radial width of the slightly scaled central ring contour.
    ring_width = 1.5 * 0.95
    inner_radius = outer_radius - ring_width
    start = angle - half_width
    end = angle + half_width

    def point(radius: float, value: float) -> tuple[float, float]:
        return (
            14.0 + radius * math.cos(value),
            14.0 + radius * math.sin(value),
        )

    ox1, oy1 = point(outer_radius, start)
    ox2, oy2 = point(outer_radius, end)
    ix1, iy1 = point(inner_radius, start)
    ix2, iy2 = point(inner_radius, end)
    return (
        f'<path id="direction-{direction}" class="foreground" '
        f'd="M{ox1:.3f} {oy1:.3f} '
        f'A{outer_radius} {outer_radius} 0 0 1 {ox2:.3f} {oy2:.3f} '
        f'L{ix2:.3f} {iy2:.3f} '
        f'A{inner_radius:.3f} {inner_radius:.3f} 0 0 0 {ix1:.3f} {iy1:.3f} Z" />'
    )


def svg_document(
    mask: str,
    *,
    direction: str = "center",
    palette: str = "success",
    error: bool = False,
) -> str:
    if len(mask) != 4 or set(mask) - {"0", "1"}:
        raise ValueError("mask must be a four-bit binary string")
    if direction != "center" and direction not in DIRECTION_ANGLES:
        raise ValueError(f"unsupported direction: {direction}")
    if palette not in {"success", "warning", "error"}:
        raise ValueError(f"unsupported palette: {palette}")
    if error and palette != "error":
        raise ValueError("error icon must use the error palette")

    nodes = [f'<g transform="{MASK_TRANSLATE}">']
    if error:
        nodes.extend((OUTER_RING, ERROR_MARK))
    else:
        bits = int(mask, 2)
        for pos, path_data in PIXEL_PATHS.items():
            if bits & (1 << pos):
                nodes.append(
                    f'<path id="pixel-{pos}" class="foreground" '
                    f'd="{path_data}" />'
                )
        nodes.extend((GRID_VERTICAL, GRID_HORIZONTAL, OUTER_RING))
    nodes.append("</g>")

    # Center is deliberately represented by the shared base icon: no arc ring.
    if direction != "center" and not error:
        # Draw only the active sector; inactive directions are not part of SVG.
        nodes.append(direction_sector(direction))

    body = "\n  ".join(nodes).replace(
        'class="foreground"', f'class="{palette}"'
    )
    return f"{SVG_HEADER}\n  {body}\n</svg>\n"


def expected_files() -> dict[str, str]:
    files = {
        "hyproled-off.svg": svg_document("0000", palette="warning"),
        "hyproled-error.svg": svg_document("0000", palette="error", error=True),
    }
    for mask in all_masks():
        files[icon_filename(mask)] = svg_document(mask)
        for direction in DIRECTIONS:
            name = icon_filename(mask, direction)
            files[name] = svg_document(mask, direction=direction)
    return dict(sorted(files.items()))


def selector_for(mask: str, direction: str = "center") -> str:
    selector = f"#custom-hyproled.mask-{mask}"
    if direction != "center":
        selector += f".pixel-shift-direction-{direction}"
    return selector


def generated_css() -> str:
    rules = [CSS_HEADER.rstrip(), ""]
    for mask in all_masks():
        for direction in ("center", *DIRECTIONS):
            filename = icon_filename(mask, direction)
            selector = selector_for(mask, direction)
            rules.extend((
                f"{selector} {{",
                f'  background-image: url("@HYPROLED_ICON_DIR@/{filename}");',
                "}",
                "",
            ))
    return "\n".join(rules).rstrip() + "\n"


def check_files(files: dict[str, str], css: str) -> bool:
    expected_names = set(files)
    actual_names = {
        path.name for path in OUTPUT_DIR.glob("hyproled-*.svg")
    }
    ok = True
    for name in sorted(expected_names - actual_names):
        print(f"missing: {OUTPUT_DIR / name}")
        ok = False
    for name in sorted(actual_names - expected_names):
        print(f"unexpected: {OUTPUT_DIR / name}")
        ok = False
    for name in sorted(expected_names & actual_names):
        if (OUTPUT_DIR / name).read_text(encoding="utf-8") != files[name]:
            print(f"out of date: {OUTPUT_DIR / name}")
            ok = False
    if not CSS_OUTPUT.is_file():
        print(f"missing: {CSS_OUTPUT}")
        ok = False
    elif CSS_OUTPUT.read_text(encoding="utf-8") != css:
        print(f"out of date: {CSS_OUTPUT}")
        ok = False
    if ok:
        print(f"OK: {len(files)} SVG icons and generated Waybar CSS match")
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify generated SVGs and CSS without modifying files",
    )
    args = parser.parse_args()
    files = expected_files()
    css = generated_css()
    if args.check:
        return 0 if check_files(files, css) else 1

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    # Remove only filenames belonging to the preceding Stage 6 scheme.
    for pattern in ("hyproled-mask-*-shift-*.svg", "hyproled-shift-*.svg"):
        for path in OUTPUT_DIR.glob(pattern):
            path.unlink()
    for name, content in files.items():
        (OUTPUT_DIR / name).write_text(content, encoding="utf-8")
    CSS_OUTPUT.write_text(css, encoding="utf-8")
    print(f"Generated {len(files)} SVG icons and {CSS_OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
